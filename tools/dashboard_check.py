#!/usr/bin/env python3
"""Verify the dashboard preview in an isolated browser context."""
from pathlib import Path
from playwright.sync_api import sync_playwright, expect
ROOT=Path(__file__).resolve().parents[1]
(ROOT / 'validation/screenshots').mkdir(parents=True, exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path='/usr/bin/google-chrome',headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1440,'height':1050})
    errors=[]
    page.on('pageerror',lambda e: errors.append(str(e)))
    response=page.goto('http://127.0.0.1:8012/dashboard/',wait_until='networkidle')
    assert response.status==200
    expect(page.get_by_role('heading',name='Manage your website')).to_be_visible()
    page.screenshot(path=str(ROOT/'validation/screenshots/dashboard-desktop.png'),full_page=True)
    page.locator('[data-nav="treatments"]').click()
    page.locator('#content-search').fill('zz-no-match')
    expect(page.get_by_text('No matching content')).to_be_visible()
    page.locator('#content-search').fill('')
    page.locator('[data-edit]').first.click()
    page.locator('#editor-form input[name="title"]').fill('QA draft treatment')
    page.get_by_role('button',name='Save draft',exact=True).click()
    page.locator('#status-filter').select_option('Draft')
    expect(page.get_by_text('QA draft treatment',exact=True)).to_be_visible()
    page.reload(wait_until='networkidle')
    expect(page.get_by_text('QA draft treatment',exact=True)).to_be_visible()
    page.locator('[data-nav="drafts"]').click()
    expect(page.locator('tbody tr')).to_have_count(1)
    page.locator('[data-nav="activity"]').click()
    expect(page.locator('.activity-list li').filter(has_text='Saved draft: QA draft treatment')).to_be_visible()
    page.locator('[data-nav="settings"]').click()
    page.locator('#settings-form input[name="name"]').fill('QA workspace')
    page.get_by_role('button',name='Save preferences').click()
    expect(page.locator('.workspace strong')).to_have_text('QA workspace')
    expect(page.locator('#export')).to_have_count(0)
    page.keyboard.press('Control+k')
    expect(page.locator('#search-dialog')).to_be_visible()
    page.locator('#global-query').fill('QA draft treatment')
    expect(page.locator('.command-result')).to_have_count(1)
    page.keyboard.press('Enter')
    expect(page.locator('#editor')).to_be_visible()
    page.locator('#editor-form input[name="title"]').fill('Unsaved change')
    page.keyboard.press('Escape')
    expect(page.locator('#editor')).to_be_visible()
    expect(page.locator('#discard-notice')).to_be_visible()
    page.get_by_role('button',name='Keep editing').click()
    expect(page.locator('#discard-notice')).to_be_hidden()
    page.locator('#cancel-editor').click()
    page.get_by_role('button',name='Discard changes').click()
    expect(page.locator('#editor')).to_be_hidden()
    page.goto('http://127.0.0.1:8012/dashboard/#treatments',wait_until='networkidle')
    page.locator('#sort-content').select_option('az')
    titles=page.locator('tbody .title-button').all_text_contents()
    assert len(titles)>1
    page.locator('#sort-content').select_option('za')
    assert page.locator('tbody .title-button').all_text_contents()==list(reversed(titles))
    page.evaluate('localStorage.removeItem("drteeth-dashboard-v1")')
    page.goto('http://127.0.0.1:8012/dashboard/#gallery',wait_until='networkidle')
    expect(page.locator('.media-card')).to_have_count(9)
    page.set_viewport_size({'width':390,'height':844})
    page.goto('http://127.0.0.1:8012/dashboard/',wait_until='networkidle')
    expect(page.get_by_role('heading',name='Manage your website')).to_be_visible()
    assert page.evaluate('document.documentElement.scrollWidth <= innerWidth')
    page.screenshot(path=str(ROOT/'validation/screenshots/dashboard-mobile.png'),full_page=True)
    page.locator('#menu').click()
    page.locator('[data-nav="doctors"]').click()
    expect(page.locator('#page-title')).to_have_text('Doctors')
    expect(page.locator('#menu')).to_have_attribute('aria-expanded','false')
    expect(page.locator('tbody tr')).to_have_count(4)
    assert not errors,errors
    browser.close()
print('PASS: desktop/mobile layout, search, filters, draft editing and persistence, activity, settings, gallery, mobile navigation. No browser errors.')
